const DICTS: Record<Locale, Record<StringKey, string>> = { en, ko, ja };

/** Maps an app language code such as "ko", "ja-JP" or "en-gb" to a supported locale. */
export function pickLocale(code: string | null | undefined): Locale {
  const base = (code ?? "").toLowerCase().split(/[-_]/)[0];
  if (base === "ko") return "ko";
  if (base === "ja") return "ja";
  return "en";
}

export function translate(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  const dict: Dict = DICTS[locale];
  let text = dict[key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
